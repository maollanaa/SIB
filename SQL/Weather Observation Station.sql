--15
SELECT ROUND(LONG_W, 4) AS long_w
FROM STATION
WHERE LAT_N = (SELECT MAX(LAT_N) FROM STATION WHERE LAT_N < 137.2345);

--16
SELECT ROUND(MIN(LAT_N), 4) AS min_lat
FROM STATION
WHERE LAT_N > 38.7780;

--17
SELECT ROUND(LONG_W, 4) AS long_w
FROM STATION
WHERE LAT_N = (SELECT MIN(LAT_N) FROM STATION WHERE LAT_N > 38.7780);

--18
SELECT ROUND(
            ABS((SELECT MIN(LAT_N) FROM STATION) - (SELECT MAX(LAT_N) FROM STATION)) +
            ABS((SELECT MIN(LONG_W) FROM STATION) - (SELECT MAX(LONG_W) FROM STATION)), 4
          ) AS manhattan_distance
FROM dual;

--19
SELECT ROUND(
            SQRT(POW((SELECT MAX(LAT_N) FROM STATION) - (SELECT MIN(LAT_N) FROM STATION), 2) + 
                 POW((SELECT MAX(LONG_W) FROM STATION) - (SELECT MIN(LONG_W) FROM STATION), 2)), 4
          ) AS euclidean_distance
FROM dual;

--20
WITH ordered_lats AS (
    SELECT LAT_N,
           ROW_NUMBER() OVER (ORDER BY LAT_N) AS row_num,
           COUNT(*) OVER () AS total_count
    FROM STATION
)
SELECT ROUND(
    AVG(LAT_N), 4) as median_lat
FROM ordered_lats
WHERE row_num IN ((total_count + 1) DIV 2, (total_count + 2) DIV 2);
