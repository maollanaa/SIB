SELECT TRUNCATE(SUM(LAT_N), 4) AS sum_lat
FROM STATION
WHERE LAT_N > 38.7880 AND LAT_N < 137.2345;

--14
SELECT TRUNCATE(MAX(LAT_N), 4) AS max_lat
FROM STATION
